//! 后端热路径调试跟踪的总开关。
//!
//! 这里控制的日志都发生在**每次 I/O 完成 / 每次 loop 迭代**上（kevent 完成、
//! 读取重新武装、提交循环、跨线程唤醒）。它们对定位后端问题是必要的，但留在
//! 生产路径上有两重代价：
//!
//!   1. 单连接即可产生每秒数千行——字符串格式化与写盘都发生在**事件循环线程**上；
//!   2. 日志消费方若与事件循环同线程（如控制面 /logs 流与引擎共用 loop），每推
//!      一帧都会产生新的日志行 ⇒ 正反馈自激。实测：单个 /logs 订阅 3 秒放大到
//!      2.9 万帧、1.16 万行日志全部是 `[kq:*]`，把 loop 拖到瘫痪。
//!
//! 故默认关闭。定位后端问题时设 `LIBXEV_TRACE=1` 打开（kqueue 后端 `Loop.init`
//! 读取）。**生产路径不得打开。**

/// 热路径跟踪总开关。
pub var enabled: bool = false;
